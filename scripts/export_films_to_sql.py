#!/usr/bin/env python3
"""
export_films_to_sql.py
======================
Turns a scraped + normalised `za-film-db` export into a plain SQL file with
one INSERT per film, written straight into the project's migrations folder —
the same way `20261102000000_za_films_seed.sql` loaded the original catalogue.

Typical flow (after running scrape_and_normalize_za_films.py, which writes
`za-film-db/data/films.json`):

    python scripts/export_films_to_sql.py /path/to/za-film-db

By default the file is written to
`supabase/migrations/<UTC timestamp>_za_films_data.sql` next to the original
seed. Hand the updated project to Lovable and the migration gets applied to
the app database — no import token, no running app required.

The statements are upserts keyed on the film id, so regenerating and
re-applying an unchanged export is safe: existing films are updated in place
and nothing is duplicated.
"""

import argparse
import json
import os
import sys
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from publish_to_archive import to_row  # single source for the film -> row mapping

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILMS_PER_STATEMENT = 25

COLUMNS = [
    "id", "title", "search_title", "year", "format", "genres", "languages",
    "runtime_minutes", "summary", "imdb_id", "wikidata_id", "category", "data",
]

UPDATE_SET = ", ".join(
    f"{col} = EXCLUDED.{col}" for col in COLUMNS if col != "id"
)


def sql_str(value) -> str:
    """Quote a text value as a SQL string literal (standard_conforming_strings=on)."""
    if value is None:
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def sql_text_array(values) -> str:
    if not values:
        return "'{}'::text[]"
    return "ARRAY[" + ", ".join(sql_str(v) for v in values) + "]::text[]"


def row_to_values(row: dict) -> list[str]:
    return [
        sql_str(row["id"]),
        sql_str(row["title"]),
        sql_str(row["search_title"]),
        str(int(row["year"])),
        sql_str(row["format"]),
        sql_text_array(row["genres"]),
        sql_text_array(row["languages"]),
        sql_str(row["runtime_minutes"]),
        sql_str(row["summary"]),
        sql_str(row["imdb_id"]),
        sql_str(row["wikidata_id"]),
        sql_str(row["category"]),
        sql_str(json.dumps(row["data"], ensure_ascii=False, separators=(",", ":"))) + "::jsonb",
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("db_dir", help="Path to the za-film-db export folder")
    parser.add_argument("--out", default=None,
                        help="Output SQL path (default: supabase/migrations/<UTC timestamp>_za_films_data.sql)")
    parser.add_argument("--limit", type=int, default=None, help="Only export the first N films (for testing)")
    args = parser.parse_args()

    films_path = os.path.join(args.db_dir, "data", "films.json")
    with open(films_path, encoding="utf-8") as f:
        films = json.load(f)
    if args.limit:
        films = films[: args.limit]
    rows = [to_row(film) for film in films]
    print(f"Loaded {len(rows)} films from {films_path}")

    if args.out:
        out_path = args.out
    else:
        stamp = datetime.now(timezone.utc).strftime("%Y%m%d%H%M%S")
        out_path = os.path.join(
            REPO_ROOT, "supabase", "migrations", f"{stamp}_za_films_data.sql"
        )
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)

    lines = [
        "-- Mzansi Film Archive: film data export (generated by scripts/export_films_to_sql.py)",
        f"-- Source: {films_path}",
        f"-- Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}",
        f"-- Films: {len(rows)}",
        "--",
        "-- Upserts by film id: re-applying an unchanged export is safe and only",
        "-- new or changed films are written. Assumes the public.films schema from",
        "-- 20261102000000_za_films_seed.sql already exists.",
        "",
    ]

    for i in range(0, len(rows), FILMS_PER_STATEMENT):
        chunk = rows[i : i + FILMS_PER_STATEMENT]
        lines.append(
            "INSERT INTO public.films (" + ", ".join(COLUMNS) + ") VALUES"
        )
        for j, row in enumerate(chunk):
            values = ", ".join(row_to_values(row))
            lines.append(f"  ({values}){',' if j < len(chunk) - 1 else ''}")
        lines.append(f"ON CONFLICT (id) DO UPDATE SET {UPDATE_SET};")
        lines.append("")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    size_kb = os.path.getsize(out_path) / 1024
    print(f"Wrote {out_path} ({size_kb:.0f} KB, {len(rows)} films).")
    print("Apply it to the app database as the next step (see scripts/README.md).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
